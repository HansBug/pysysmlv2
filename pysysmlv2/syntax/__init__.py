"""Syntax parsing, diagnostics, and explicit SysML source AST APIs.

This package owns the generated ANTLR boundary, the handwritten listener, and
the concrete source AST.  The AST deliberately preserves grammar-level
structure and provenance without performing workspace linking or semantic
identity assignment.  Concrete nodes expose their own ``to_sysml`` methods;
the formatter can therefore emit canonical, parseable SysML while keeping
trivia concerns outside this layer.

.. list-table:: Syntax roadmap
   :header-rows: 1

   * - Module
     - Responsibility
   * - :mod:`pysysmlv2.syntax.parser`
     - ANTLR invocation and structured lexer/parser diagnostics.
   * - :mod:`pysysmlv2.syntax.listener`
     - Explicit context-to-node callbacks driven by ``ParseTreeWalker``.
   * - :mod:`pysysmlv2.syntax.ast`
     - Handwritten source nodes, provenance, and per-node round-trip export.
   * - :mod:`pysysmlv2.syntax.generated`
     - Regenerated parser artifacts; never hand-edit this directory.
"""

