def _occurrence_usage(
    name: str,
    *,
    prefix: Optional[OccurrenceUsagePrefix] = None,
    specialization: Optional[FeatureSpecializationPart] = None,
    body: Optional[DefinitionBody] = None,
) -> OccurrenceUsage:
    """Build one typed occurrence usage with its explicit grammar fields."""
    return OccurrenceUsage(
        occurrence_usage_prefix=prefix or OccurrenceUsagePrefix(),
        usage=Usage(
            body=body if body is not None else DefinitionBody(declaration_only=True),
            declaration=UsageDeclaration(
                identification=Identification(declared_name=name),
                specialization=specialization,
            ),
        ),
    )


def _occurrence_definition(
    name: str,
    *,
    specialization: Optional[SubclassificationPart] = None,
    body: Optional[DefinitionBody] = None,
) -> OccurrenceDefinition:
    """Build one typed occurrence definition from its explicit fields."""
    return OccurrenceDefinition(
        occurrence_definition_prefix=OccurrenceDefinitionPrefix(),
        definition=Definition(
            declaration=DefinitionDeclaration(
                identification=Identification(declared_name=name),
                subclassification=specialization,
            ),
            body=body if body is not None else DefinitionBody(declaration_only=True),
        ),
    )


