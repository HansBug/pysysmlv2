"""Field-level AST and round-trip tests for the reviewed 8.4 semantic examples.

The source snippets and the exclusion records are repository-owned copies of
the visually reviewed OMG Language PDF pages 435--440 (printed pages
403--408).  The expected AST values below are authored directly from the
grammar-facing dataclasses; they are deliberately not generated by parsing a
fixture, so a parser regression cannot silently regenerate its own oracle.
"""

