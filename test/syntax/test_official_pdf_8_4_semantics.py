def _ids(entries: Iterable[Dict[str, Any]]) -> Tuple[str, ...]:
    """Return stable IDs for parametrized source assertions."""
    return tuple("{}: {}".format(entry["id"], entry["fixture_name"]) for entry in entries)


@pytest.mark.parametrize("entry", ENTRIES, ids=_ids(ENTRIES))
def test_fixture_source_is_exactly_the_reviewed_pdf_panel(entry: Dict[str, Any]):
    """Ensure each local fixture remains byte-for-byte tied to the ledger."""
    path = FIXTURE_ROOT / entry["fixture_name"]
    assert path.is_file()
    assert path.read_text(encoding="utf-8") == entry["source_code"] + "\n"


def test_ledger_has_exactly_eight_complete_sysml_blocks_and_eight_exclusions():
    """Make the visual audit boundary explicit and keep KerML out of fixtures."""
    assert len(ENTRIES) == 8
    assert len(EXCLUSIONS) == 8
    assert all(entry["fixture_eligible"] is True for entry in ENTRIES)
    assert all(entry["fixture_eligible"] is False for entry in EXCLUSIONS)
    assert all("fixture_name" in entry for entry in ENTRIES)
    assert all("fixture_name" not in entry for entry in EXCLUSIONS)
    assert all(
        ("KerML" in entry["source_code"] or "..." in entry["source_code"]) for entry in EXCLUSIONS
    )


@pytest.mark.parametrize("entry", ENTRIES, ids=_ids(ENTRIES))
def test_fixture_has_independent_field_level_ast_and_roundtrip(entry: Dict[str, Any]):
    """Compare every AST dataclass field, then require canonical reparsing."""
    path = FIXTURE_ROOT / entry["fixture_name"]
    result = parse(path.read_text(encoding="utf-8"), str(path))
    assert result.ok, result.diagnostics
    expected_factory = EXPECTED[entry["fixture_name"]]
    expected = expected_factory()
    assert result.ast == expected

    exported = str(result.ast)
    reparsed = parse(exported, "roundtrip/{}".format(path.name))
    assert reparsed.ok, reparsed.diagnostics
    assert reparsed.ast == expected
    assert str(reparsed.ast) == exported
