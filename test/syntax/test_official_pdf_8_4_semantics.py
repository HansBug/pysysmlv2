ROOT = Path(__file__).resolve().parents[2]
FIXTURE_ROOT = ROOT / "test" / "testfile" / "omg_sysml2_language" / "manual"
LEDGER_PATH = ROOT / "docs" / "research" / "manual_pdf_review" / "section_8_4_3_8_4_6.json"


def _ledger() -> Dict[str, Any]:
    """Load the locally reviewed 8.4 ledger."""
    payload = json.loads(LEDGER_PATH.read_text(encoding="utf-8"))
    assert payload["scope"]["physical_pages"] == [435, 440]
    assert payload["scope"]["printed_pages"] == [403, 408]
    return payload


LEDGER = _ledger()
ENTRIES: Tuple[Dict[str, Any], ...] = tuple(LEDGER["entries"])
EXCLUSIONS: Tuple[Dict[str, Any], ...] = tuple(LEDGER["excluded_fragments"])


def _q(*segments: str) -> QualifiedReference:
    """Build one explicitly segmented qualified reference."""
    return QualifiedReference(list(segments))


def _dotted(*segments: str) -> DottedQualifiedReference:
    """Build a dotted-qualified reference whose final segment is qualified."""
    return DottedQualifiedReference([_q(*segments)])


def _specialization(operator: str, reference: Any) -> FeatureSpecialization:
    """Build one concrete feature-specialization field."""
    return FeatureSpecialization(operator, [reference])


def _subclassification(*segments: str) -> SubclassificationPart:
    """Build the explicit ``specializes`` field used by a definition."""
    return SubclassificationPart("specializes", [_q(*segments)])


def _definition(name: str, *segments: str, body: DefinitionBody) -> Definition:
    """Build a named definition with its explicit specialization and body."""
    return Definition(
        declaration=DefinitionDeclaration(
            identification=Identification(declared_name=name),
            subclassification=_subclassification(*segments),
        ),
        body=body,
    )


def _attribute_usage(
    name: str,
    *,
    reference: bool,
    specializations: Iterable[FeatureSpecialization],
    body: Optional[DefinitionBody] = None,
) -> AttributeUsage:
    """Build one attribute usage from its grammar-level fields."""
    return AttributeUsage(
        usage_prefix=UsagePrefix(is_reference=reference),
        usage=Usage(
            body=body if body is not None else DefinitionBody(declaration_only=True),
            declaration=UsageDeclaration(
                identification=Identification(declared_name=name),
                specialization=FeatureSpecializationPart(list(specializations)),
            ),
        ),
    )


def _expected_d1() -> Model:
    """Return the hand-authored AST expectation for the D1 example."""
    return Model(
        members=[
            PackageMember(
                element=AttributeDefinition(
                    definition_prefix=DefinitionPrefix(),
                    definition=_definition(
                        "D1",
                        "Base",
                        "DataValue",
                        body=DefinitionBody(
                            items=[
                                DefinitionBodyItem(
                                    element=ReferenceUsage(
                                        usage_prefix=UsagePrefix(),
                                        usage=Usage(
                                            body=DefinitionBody(declaration_only=True),
                                            declaration=UsageDeclaration(
                                                identification=Identification(declared_name="a"),
                                                specialization=FeatureSpecializationPart(
                                                    [
                                                        _specialization(
                                                            "subsets", _q("Base", "things")
                                                        )
                                                    ]
                                                ),
                                            ),
                                        ),
                                        has_ref_keyword=True,
                                    )
                                )
                            ]
                        ),
                    ),
                )
            )
        ]
    )


def _expected_d2_and_d() -> Model:
    """Return the hand-authored AST expectation for the D2/d panel."""
    d2_attribute = _attribute_usage(
        "a",
        reference=True,
        specializations=[
            _specialization(":", OwnedFeatureTyping(_dotted("ScalarValue", "String"))),
            _specialization("subsets", _q("Base", "dataValues")),
        ],
    )
    d_usage = _attribute_usage(
        "d",
        reference=True,
        specializations=[
            _specialization(":", OwnedFeatureTyping(_dotted("D2"))),
            _specialization("subsets", _q("Base", "dataValues")),
        ],
        body=DefinitionBody(
            items=[
                DefinitionBodyItem(
                    element=_attribute_usage(
                        "b",
                        reference=True,
                        specializations=[_specialization("subsets", _q("a"))],
                    )
                )
            ]
        ),
    )
    return Model(
        members=[
            PackageMember(
                element=AttributeDefinition(
                    definition_prefix=DefinitionPrefix(),
                    definition=_definition(
                        "D2",
                        "Base",
                        "DataValue",
                        body=DefinitionBody(items=[DefinitionBodyItem(element=d2_attribute)]),
                    ),
                )
            ),
            PackageMember(element=d_usage),
        ]
    )


