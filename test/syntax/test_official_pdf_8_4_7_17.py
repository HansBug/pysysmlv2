"""Independent AST oracles for representative Section 8.4 semantic panels.

The source files are copied from the human-reviewed OMG Language PDF ledger.
These expectations are assembled directly from the public AST dataclasses;
they are deliberately not generated by parsing the fixture first.  The broad
manual-inventory suite checks every eligible panel for source preservation and
round-trip fixed points, while this module anchors concrete field-level
equality for the state and requirement definition families most relevant to
the downstream state-machine and obligation-model work.
"""

from __future__ import annotations

from pathlib import Path
from typing import Callable, Dict

import pytest

from pysysmlv2 import parse
from pysysmlv2.syntax.ast import (
    DefinitionDeclaration,
    Identification,
    Model,
    OccurrenceDefinitionPrefix,
    PackageMember,
    QualifiedReference,
    RequirementBody,
    RequirementDefinition,
    StateDefBody,
    StateDefinition,
    SubclassificationPart,
)

pytestmark = pytest.mark.unit


ROOT = Path(__file__).resolve().parents[2]
FIXTURE_ROOT = ROOT / "test" / "testfile" / "omg_sysml2_language" / "manual"


def _reference(*segments: str) -> QualifiedReference:
    """Build one explicitly segmented qualified reference for an oracle."""
    return QualifiedReference(list(segments))


def _state_definition(name: str, *supertype: str) -> StateDefinition:
    """Build the exact state-definition shape used by the printed examples."""
    return StateDefinition(
        occurrence_definition_prefix=OccurrenceDefinitionPrefix(),
        definition_declaration=DefinitionDeclaration(
            identification=Identification(declared_name=name),
            subclassification=SubclassificationPart("specializes", [_reference(*supertype)]),
        ),
        state_def_body=StateDefBody(is_declaration_only=True),
    )


def _requirement_definition(name: str, *supertype: str) -> RequirementDefinition:
    """Build the exact requirement-definition shape used by the PDF panel."""
    return RequirementDefinition(
        occurrence_definition_prefix=OccurrenceDefinitionPrefix(),
        definition_declaration=DefinitionDeclaration(
            identification=Identification(declared_name=name),
            subclassification=SubclassificationPart("specializes", [_reference(*supertype)]),
        ),
        body=RequirementBody(declaration_only=True),
    )


def _expected_states() -> Model:
    """Return the hand-authored AST for the S/S1 state-definition panel."""
    return Model(
        members=[
            PackageMember(element=_state_definition("S", "States", "StateAction")),
            PackageMember(element=_state_definition("S1", "S")),
        ]
    )


def _expected_requirements() -> Model:
    """Return the hand-authored AST for the R/R1 requirement panel."""
    return Model(
        members=[
            PackageMember(element=_requirement_definition("R", "Requirements", "RequirementCheck")),
            PackageMember(element=_requirement_definition("R1", "R")),
        ]
    )


EXPECTED: Dict[str, Callable[[], Model]] = {
    "section_8_4/s438_state_definitions_s_s1.sysml": _expected_states,
    "section_8_4/s447_requirement_definitions_r_r1.sysml": _expected_requirements,
}


@pytest.mark.parametrize("fixture_name", tuple(EXPECTED), ids=tuple(EXPECTED))
def test_section_8_4_fixture_has_independent_field_level_ast_oracle(fixture_name: str):
    """Compare every dataclass field before and after canonical round-trip."""
    path = FIXTURE_ROOT / fixture_name
    expected = EXPECTED[fixture_name]()
    first = parse(path.read_text(encoding="utf-8"), str(path))
    assert first.ok, first.diagnostics
    assert first.ast == expected

    exported = str(first.ast)
    second = parse(exported, "roundtrip/{}".format(path.name))
    assert second.ok, second.diagnostics
    assert second.ast == expected
    assert str(second.ast) == exported
